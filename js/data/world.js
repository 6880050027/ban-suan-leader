export function polite(id, text) {
  const f = GENDER[id] === 'f';
  return String(text).replace(/ครับ\/ค่ะ/g, f ? 'ค่ะ' : 'ครับ').replace(/ครับ\/คะ/g, f ? 'คะ' : 'ครับ');
}

